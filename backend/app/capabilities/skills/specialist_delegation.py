"""specialist_delegation — how a Super Agent hands work to its specialist agents
and decides when it has enough to answer."""

from __future__ import annotations

from ..base import Skill

SPECIALIST_DELEGATION = Skill(
    name="specialist_delegation",
    description="전문 에이전트에게 업무를 자연어로 위임하고, 결과가 충분해지면 종합해 답하는 방법.",
    instructions="""\
- 직접 분석하거나 답을 지어내지 않는다. 데이터나 기록에 근거해야 하는 검토 항목은 반드시 등록된 위임 Tool을 호출해 전문 에이전트에게 맡긴다.
- 요청에 포함된 검토 항목을 각 항목의 담당 전문 에이전트에게 위임한다. 어떤 전문 에이전트가 무엇을 담당하는지는 위임 Tool의 설명을 따른다.
  요청이 요구하지 않는 항목의 전문 에이전트에게는 위임하지 않는다. 등록된 위임 Tool을 모두 써야 하는 것은 아니다.
- 한 번에 하나의 전문 에이전트에게만 위임하고, 그 결과를 받은 뒤 다시 판단한다: 요청의 항목 중 아직 담당 전문 에이전트의 결과를 받지 못한 것이 있으면
  다음 위임을 하고, 모든 항목에 대한 결과가 있으면 더 이상 위임하지 않는다. 이미 결과를 받은 전문 에이전트에게 같은 업무를 다시 위임하지 않는다.
- 위임 문장(task)은 전문 에이전트가 바로 수행할 수 있도록 구체적으로 쓴다. 대상 기업명과 확인해야 할 항목을 포함하고, 그 전문 에이전트의 담당 범위를 벗어난 요구는 넣지 않는다.
- 앞서 다른 전문 에이전트에게서 받은 결과 중 이번 업무를 수행하는 데 필요한 사실(예: 회의에서 정한 기준, 확인된 리스크)이 있으면
  위임 문장에 함께 담는다. 무엇을 담을지는 위임받는 전문 에이전트의 담당 범위를 보고 판단한다.
- 위임 문장은 한국어로 작성한다. 전달할 맥락이 없으면 2~3문장으로 간결하게 쓴다.
- 필요한 결과를 모두 받았으면 Tool을 호출하지 않고 최종 응답을 작성한다. 최종 응답은 원래 요청에 대한 회신으로,
  요청의 각 항목에 대해 전문 에이전트 결과에 근거해 답하고 요청이 묻는 판단(예: 진행 여부와 조건)을 분명히 밝힌다.
  전문 에이전트 결과에 없는 사실을 추가하지 않는다.""",
)
