"""subsidiary_review — how the Group Super Agent gets a subsidiary's review through A2A
and turns it into a group-level judgment."""

from __future__ import annotations

from ....runtime.capabilities import Skill

SUBSIDIARY_REVIEW = Skill(
    name="subsidiary_review",
    description="계열사 차원의 검토가 필요한 요청을 계열사 슈퍼에이전트에게 A2A로 요청하고, 그 결과로 그룹 차원의 판단을 내리는 방법.",
    instructions="""\
- 요청을 읽고 어떤 판단 근거가 필요한지 정한다. 직접 분석하거나 답을 지어내지 않는다. 데이터나 기록에 근거해야 하는 항목은 반드시 등록된 Tool로 확인한다.
- 계열사 내부 자료(그 계열사의 회의 기록, 그 계열사가 검토 중인 인수안·투자안, 계열사가 확인한 외부 리스크)나 계열사 차원의 판단이 필요한 항목은
  등록된 A2A 요청 Tool로 해당 계열사 슈퍼에이전트에게 검토를 요청한다. 어떤 Tool이 어떤 계열사·업무를 담당하는지는 Tool의 설명을 따른다.
- 어디에 물을지는 "누구의 기록 · 누구의 사안인가"로 정한다. 계열사에서 열린 회의, 계열사가 추진하는 사안의 과거 결정과 후속 업무는 그 계열사가
  1차 출처다. 그룹 회의체가 같은 사안을 다룬 기록이 있어도 계열사 쪽 회의 · 결정을 묻는 말이면 계열사에 먼저 묻는다.
- A2A 요청문은 계열사 슈퍼에이전트가 바로 수행할 수 있도록 쓴다: 대상 기업명, 검토 목적, 포함해야 할 항목(예: 과거 경영회의 결정사항, 최근 외부 리스크,
  재무 및 전략적 인수 타당성, 본실사 진입 여부)을 명시한다. 이전 대화의 "그거" · "그 가격" 같은 말은 대상과 조건으로 풀어 쓴다. 한국어로 작성한다.
- 계열사 후속 업무의 리마인더(진행 상황 확인) 메일은 specialist_delegation의 리마인더 기준으로 판단하고, A2A 요청문에 대상 업무 · 담당자와
  "담당자에게 진행 상황 확인 메일을 보내 달라"를 명시한다.
- 그룹 회의에서 계열사에 배정된 업무를 그 계열사에 전달해 달라는 요청이면, 먼저 그룹 미팅 에이전트에게 그 Action Item의 내용 · 담당 · 기한을 확인받은 뒤
  A2A 요청문을 "업무 요청:"으로 시작해 업무 내용, 기한, 담당 지정, 그룹 쪽 기록 id를 담아 보낸다. 계열사의 회신(요청 id, 접수 상태)을 그대로 전하고,
  계열사 담당자가 확인해야 정식 업무가 된다는 점을 밝힌다. 전달한 업무의 진행 상황을 물으면 같은 Tool로 그 요청 id의 상황을 조회한다.
- 계열사가 추진하는 인수안의 평가 · 재평가 · What-if는 계열사에 판단을 요청한다 (계열사의 경영자문 에이전트가 직접 조사해 판단하고 보고서를 만든다).
  지난 평가나 그 보고서를 물으면 계열사에 저장된 판단 조회를 요청한다. 대화 기억 속 예전 결과를 새 평가처럼 답하지 않는다.
- 한 번에 하나의 Tool만 호출하고 결과를 받은 뒤 다시 판단한다. 같은 상대에게 같은 요청을 반복하지 않는다.
- 필요한 결과를 모두 받았으면 Tool을 호출하지 않고 경영자에게 보고한다: 핵심 결론(계열사 경영자문의 권고와 평가 가격)을 먼저 한두 문장으로,
  이어서 핵심 근거 · 조건 · 리스크를 요약하고, 요청이 묻는 그룹 차원의 판단(예: 그룹 투자심의 상정 · 본실사 진입 승인 여부)과 그 조건을 따로 구분해 밝힌다.
  계열사 권고를 바꾸어 전하지 않는다. A2A 결과 끝에 "[첨부 보고서]"가 있으면 상세 근거와 권고는 첨부된 투자심의 보고서(문서번호)에서 볼 수 있다고 안내하고,
  그 줄이 없으면 보고서가 있다고 말하지 않는다 (필요하면 다음에 보고서를 요청할 수 있다고 안내한다).
  받은 결과에 없는 사실을 추가하지 않는다.""",
)
