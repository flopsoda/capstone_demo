"""specialist_delegation — how a Super Agent hands work to its specialist agents
and decides when it has enough to answer."""

from __future__ import annotations

from ...runtime.capabilities import Skill

SPECIALIST_DELEGATION = Skill(
    name="specialist_delegation",
    description="전문 에이전트에게 업무를 자연어로 위임하고, 결과가 충분해지면 종합해 답하는 방법.",
    instructions="""\
- 직접 분석하거나 답을 지어내지 않는다. 데이터나 기록에 근거해야 하는 검토 항목은 반드시 등록된 위임 Tool을 호출해 전문 에이전트에게 맡긴다.
- 요청에 포함된 검토 항목을 각 항목의 담당 전문 에이전트에게 위임한다. 어떤 전문 에이전트가 무엇을 담당하는지는 위임 Tool의 설명을 따른다.
  요청이 요구하지 않는 항목의 전문 에이전트에게는 위임하지 않는다. 등록된 위임 Tool을 모두 써야 하는 것은 아니다.
- 한 번에 하나의 전문 에이전트에게만 위임하고, 그 결과를 받은 뒤 다시 판단한다: 요청의 항목 중 아직 담당 전문 에이전트의 결과를 받지 못한 것이 있으면
  다음 위임을 하고, 모든 항목에 대한 결과가 있으면 더 이상 위임하지 않는다. 이미 결과를 받은 전문 에이전트에게 같은 업무를 다시 위임하지 않는다.
- 위임 문장(task)은 전문 에이전트가 바로 수행할 수 있도록 구체적으로 쓴다. 대상 기업명과 확인해야 할 항목을 포함하고, 그 전문 에이전트의 담당 범위를 벗어난 요구는 넣지 않는다.
- 앞서 다른 전문 에이전트에게서 받은 결과 중 이번 업무를 수행하는 데 필요한 사실(예: 회의에서 정한 기준, 확인된 리스크)이 있으면
  위임 문장에 함께 담는다. 무엇을 담을지는 위임받는 전문 에이전트의 담당 범위를 보고 판단한다.
- 위임 문장은 한국어로 작성한다. 전달할 맥락이 없으면 2~3문장으로 간결하게 쓴다.
- 위임 Tool이 "위임하지 않음: … 권한이 없습니다"를 돌려주면 그 전문 에이전트에게 다시 위임하지 않는다. 받을 수 있는 결과로만 답하고,
  그 에이전트가 맡는 항목은 권한이 없어 빠졌다고 최종 응답에 밝힌다.
- 위임 문장은 이전 대화 없이도 이해되게 쓴다: "그거" · "이 건" 같은 말은 대상 기업 · 안건 · 업무 · 조건(예: 인수가격)으로 풀어 쓴다.
- 사용자가 내용을 말하지 않고 대상에 새 소식 · 최신 뉴스가 있다고만 하면(예: "그 회사 쪽에 뭔가 새 소식이 있다던데") 무슨 소식인지 되묻지 말고,
  그 사안을 맡은 쪽(계열사가 추진하는 사안이면 그 계열사)에 대상의 최신 뉴스를 확인해 지금까지의 판단과 조건에 반영해 달라고 맡긴다.
- 조회 · 분석은 필요하면 위임한다. 회의록 저장 · 확정, 일정 등록 · 변경 · 취소, 업무 배정 · 전달처럼 기록을 바꾸는 일은
  요청이 그 일을 직접 시켰을 때만 위임한다. 필요해 보이면 하지 말고, 최종 응답 끝에 "다음에 할 수 있는 일"로 제안만 한다.
- 리마인더(진행 상황 확인) 메일은 직접 시키지 않아도 사용자의 뜻으로 판단한다. 받는 사람이 정해진 업무의 담당자이고, 하루 한 번만 나가는 알림이기 때문이다.
  다음 순서로 판단한다.
  1) 대상: 지연 · 미완료 업무가 이전 대화나 이번 말에 업무명 또는 담당자 이름으로 나왔는가. 나오지 않았으면(예: 인수안 전반만 이야기한 경우)
     메일을 보내지 않고, 미완료 업무를 조회해 보여 주며 어느 업무 · 담당자에게 보낼지 묻는다. "담당자 전체"처럼 뭉뚱그려 맡기지 않는다.
  2) 뜻: 대상이 나왔고, 사용자가 그 업무가 어떻게 되고 있는지 담당자 쪽에 확인 · 문의하려는 뜻을 밝히면 다시 묻지 않고 보낸다
     (예: "담당자 쪽에 한번 알아봐야겠다", "어떻게 돼 가는지 들어 봐야겠네", "진척을 직접 챙겨 봐야겠다").
     현황이 이미 대화에 나온 뒤의 "확인이 필요하다 · 확인해 봐야겠다"는 기록을 다시 보자는 말이 아니라 담당자에게 묻자는 뜻이다.
     질문이 함께 있어도(예: "왜 이렇게 늦지? 한번 확인해 봐야겠다") 확인 의사를 따른다: 담당자에게 그 이유를 묻는 리마인더를 보낸다.
  3) 확인 의사 없이 이유 · 현황만 묻는 질문(예: "왜 이렇게 됐어?")은 이전 대화의 내용만으로 답하지 말고 담당 에이전트에게 최신 현황
     (진행 메모 · 지연 사유)을 조회해 답한다. 감상 · 평가(예: "꽤 밀렸네")에는 답만 한다. 둘 다 메일은 보내지 않고, 필요하면 끝에 리마인더를 제안한다.
  맡길 때는 위임 · 요청 문장에 대상 업무(업무명 · 담당자)와 "담당자에게 진행 상황 확인 메일을 보내 달라"를 명시한다.
  보낸 뒤에는 받는 사람과 대상 업무를, 오늘 이미 보낸 메일이면 그 사실을 최종 응답에 밝힌다.
  메일 회신은 시스템이 읽지 않으므로 "회신이 오면 보고하겠다"고 약속하지 않는다 (담당자는 메일의 버튼이나 회의지원 Agent로 진행을 알린다).
- 필요한 결과를 모두 받았으면 Tool을 호출하지 않고 최종 응답을 작성한다. 최종 응답은 원래 요청에 대한 회신으로,
  요청의 각 항목에 대해 전문 에이전트 결과에 근거해 답하고 요청이 묻는 판단(예: 진행 여부와 조건)을 분명히 밝힌다.
  전문 에이전트 결과에 없는 사실을 추가하지 않는다. "확인되는 대로 보고드리겠습니다"처럼 나중에 스스로 알려 주겠다고 하지 않는다 —
  이 시스템은 먼저 연락하지 않으므로, 진행은 사용자가 다시 물으면 조회해 답한다고 안내한다.""",
)
