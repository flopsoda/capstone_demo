
"""M&A 경영자문 Agent의 평가 및 What-if 분석 지침."""

from __future__ import annotations

from ...runtime.capabilities import Skill
from ..tools.run_mna_review import TOOL_NAME

MNA_FEASIBILITY_REVIEW = Skill(
    name="mna_feasibility_review",
    description=(
        "기업 인수 타당성을 검토하고, 사용자가 제시한 "
        "인수가격·수익성·고객 의존도 변경 시나리오를 비교하는 방법."
    ),
    instructions=f"""\
- 실제 기업에 대한 인수 검토(재무 타당성, 전략적 가치,
  기술적 의미, 리스크, 권고)는 반드시 등록된
  Workflow Tool({TOOL_NAME})로 수행한다.
  데이터에 없는 기업 사실(매출, 가격, 고객, 소송 등)을
  기억이나 추측으로 만들어내지 않는다.
  일반적인 M&A 개념, 평가 방법론, 경영 전략에 대한
  질문은 Tool 없이 답해도 된다.

- 요청과 대화 맥락에서 대상 기업, 검토 목적,
  평가 관점(persona: CEO / CFO / CTO)을 파악해
  Tool 인자로 전달한다.
  개별 평가에서는 해당 persona를 선택한다.
  관점이 명시되지 않으면 의사결정 주체에 가장 가까운
  관점 하나를 선택한다.
  계열사 차원의 인수 추진 여부 판단이면 CEO를 선택한다.
  CEO·CFO·CTO 종합 평가 요청은 persona="ALL"을 사용한다.

- 일반적인 인수 검토 요청은 기존 평가로 처리한다.
  사용자가 변경할 조건을 명시한 경우에만
  What-if 시나리오 입력값을 Tool에 전달한다.

- 인수가격 변경:
  "2.2조 원에 인수하면?"이라는 요청은
  asking_trillion_krw=2.2로 전달한다.
  금액 단위는 조 원이다.

- 영업이익률 변경:
  "영업이익률이 5%라면?"이라는 요청은
  operating_margin=0.05로 전달한다.
  퍼센트는 100으로 나눈 비율로 변환한다.

- 고객 의존도 변경:
  "최대 고객 매출 비중이 25%라면?"이라는 요청은
  revenue_share=0.25로 전달한다.

- 여러 변경 조건이 함께 제시되면 하나의 Tool 호출에
  모든 변경 조건을 전달한다.
  제시되지 않은 조건은 임의로 만들어 넣지 않는다.

- 회의에서 정한 가격 상한과 실제 가정 인수가격을
  구분한다. 단순한 상한은 context로 전달하고,
  가정 인수가격으로 임의 해석하지 않는다.

- 요청에 함께 전달된 맥락(과거 회의에서 정한 기준,
  외부에서 확인된 리스크, 조건 등)은 요약하거나 빼지 않고
  그대로 context 인자에 넣는다.
  단, 현재 What-if Workflow는 context를 평가에
  반영하지 않으므로 반영한 것처럼 설명하지 않는다.

- Tool 결과가 일반 평가인 경우:
  선택된 persona의 관점을 우선 반영한다.
  Tool 결과의 평가 항목 순서가 해당 관점의
  우선순위이며, 응답도 그 순서를 따른다.

  최종 응답 형식 (순서 고정):
  1) 권고 — 한 줄 (평가 관점 포함)
  2) 핵심 판단 근거 — 목록
  3) 주요 우려 — 목록 (위험 수준 포함)
  4) 권고 조건 — 목록
  불필요한 서론과 결론은 생략한다.

- Tool 결과의 mode가 what_if인 경우:
  1) 사용자가 지정한 변경 조건
  2) 기존 평가 결과
  3) 변경 후 평가 결과
  4) 위험이 개선되거나 악화된 항목
  5) 최종 권고의 변화 여부
  순서로 설명한다.

- Tool 결과에 없는 기업 사실을 답하지 않는다.
  Tool의 권고와 위험 수준은 임의로 변경하지 않는다.
  Tool이 반환한 인수 조건은 변경하거나 누락하지 않는다.
  추가적인 경영 제안은 검증된 분석 결과와 구분한다.
  결과에 없는 인수 효과를 확정적으로 주장하지 않는다.

- What-if 결과는 입력 가정에 따른 규칙 기반 평가이며,
  실제 기업의 미래 실적을 예측한 것은 아니다.

- 최종 응답은 한국어로 간결하게 작성한다.

- 기업 인수 타당성 평가 요청을 받으면 반드시 run_mna_review를 호출한다.

- 기업이 존재하지 않거나 데이터가 없을 것으로 예상되더라도,
LLM이 임의로 판단하지 않고 Tool을 통해 확인한다.

- Tool에서 데이터가 없다는 결과를 반환하면
재무정보를 만들어내지 않고 데이터 부족 사실을 안내한다.
""",
)
